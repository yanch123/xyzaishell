#!/usr/bin/env python3
"""Generate installer resources from locked runtime dependencies; Python 3.10+."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[3]
TOOLS = Path(__file__).resolve().parent
MARKER = 'Generated by xyzaishell prepare_third_party.py\n'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--offline', action='store_true')
    parser.add_argument('--target')
    parser.add_argument('--output', type=Path, default=ROOT / 'src-tauri/resources/third-party')
    args = parser.parse_args()
    destination = args.output.resolve()
    if destination.exists() and (not (destination / '.generated').is_file()
                               or (destination / '.generated').read_text() != MARKER):
        parser.error('Refusing to replace an output without this generator marker.')
    rust_version = subprocess.check_output(['rustc', '-vV'], text=True)
    target = args.target or os.environ.get('TAURI_ENV_TARGET_TRIPLE') or os.environ.get('CARGO_BUILD_TARGET')
    target = target or next(line[6:] for line in rust_version.splitlines() if line.startswith('host: '))
    subprocess.run(['cargo', 'fetch', '--locked'] + (['--offline'] if args.offline else []), cwd=ROOT, check=True)
    overrides = json.loads((TOOLS / 'license-overrides/sources.json').read_text(encoding='utf-8'))
    overrides = {(p['name'], p['version']): p for p in overrides}
    with tempfile.TemporaryDirectory(prefix='xyz-notices-') as temporary:
        temporary = Path(temporary)
        evidence = temporary / 'evidence'
        subprocess.run([sys.executable, str(TOOLS / 'dependency_inventory.py'),
                        '--repo', str(ROOT), '--output', str(evidence), '--target', target], check=True)
        inventory = json.loads((evidence / 'inventory.json').read_text(encoding='utf-8'))
        records = [p for p in inventory['packages']
                   if p['ecosystem'] == 'npm' or target in p.get('normal_dependency_targets', [])]
        stage = temporary / 'bundle'
        stage.mkdir()
        text = ['xyzaishell third-party notices',
                'Project licensing is unchanged by this file.',
                f'Runtime target: {target}',
                'Includes normal dependency paths; excludes build/dev/proc-macro-only paths.',
                'Dependency declarations and applicable upstream texts are preserved without rewriting license choices.',
                'The Rust Standard Library notices are in RUST-STANDARD-LIBRARY.html.',
                'MPL-covered dependency source archives accompany this file in sources/.', '']
        for package in records:
            text += ['=' * 78, f'{package["name"]} {package["version"]}',
                     f'Declared license: {package["license_declared"]}',
                     f'Source: {package.get("source_url") or package.get("source")}', '']
            for item in package['files']:
                path = evidence / package['evidence_directory'] / item['path']
                data = path.read_bytes()
                if digest(data) != item['sha256']:
                    raise RuntimeError('Evidence hash mismatch')
                text += [f'--- {item["path"]} ---', data.decode('utf-8', errors='replace'), '']
            if not package['files']:
                override = overrides.get((package['name'], package['version']))
                if not override:
                    raise RuntimeError(f'Missing reviewed license text: {package["name"]} {package["version"]}')
                data = (TOOLS / 'license-overrides' / override['file']).read_bytes()
                if digest(data) != override['sha256']:
                    raise RuntimeError('Reviewed license override hash mismatch')
                if (override.get('crate_vcs') != package.get('upstream_vcs')
                        or override['crate_checksum'] != package['lock_checksum']):
                    raise RuntimeError('License override no longer matches package VCS evidence')
                text += [f'Supplemental text source: {override["url"]}', data.decode('utf-8'), '']
                for notice in override.get('copyright_notices', []):
                    text += [notice]
                package['supplemental_license'] = override
            if 'MPL-2.0' in (package.get('license_declared') or ''):
                archive = package.get('source_archive')
                if not archive:
                    raise RuntimeError('MPL source archive missing; refusing incomplete source offer')
                source = evidence / archive['path']
                if digest(source.read_bytes()) != package['lock_checksum']:
                    raise RuntimeError('MPL source checksum mismatch')
                to = stage / archive['path']
                to.parent.mkdir(exist_ok=True)
                shutil.copyfile(source, to)
                text += [f'MPL source: {archive["path"]}',
                         f'Exact-version source download: {package["source_url"]}',
                         'These dependency sources are provided under MPL-2.0; see the included dependency license.', '']
        for package in records:
            package.pop('evidence_directory', None)
            package.pop('needs_review', None)
            package['notice_file'] = 'THIRD-PARTY-NOTICES.txt'
            package['file_path_scope'] = 'Original upstream package paths; text reproduced in notice_file.'
        vendor_components = []
        if 'windows' in target:
            sdk = json.loads((TOOLS / 'license-overrides/webview2-sdk.json').read_text(encoding='utf-8'))
            if target != 'x86_64-pc-windows-msvc':
                raise RuntimeError('Review loader hashes before adding another Windows architecture')
            metadata = json.loads(subprocess.check_output(
                ['cargo', 'metadata', '--locked', '--offline', '--format-version', '1'], cwd=ROOT))
            package = next(p for p in metadata['packages'] if p['name'] == sdk['rust_crate'])
            if package['version'] != sdk['rust_crate_version']:
                raise RuntimeError('WebView2 SDK evidence must be refreshed for the new wrapper')
            root = Path(package['manifest_path']).parent
            for filename, expected in sdk['x64_loader_sha256'].items():
                if digest((root / 'x64' / filename).read_bytes()) != expected:
                    raise RuntimeError('Microsoft loader differs from reviewed SDK package')
            text += ['=' * 78, f'{sdk["name"]} {sdk["version"]} loader redistribution',
                     f'Exact-version SDK: {sdk["url"]}', '']
            for item in sdk['files']:
                data = (TOOLS / 'license-overrides' / item['file']).read_bytes()
                if digest(data) != item['sha256']:
                    raise RuntimeError('Microsoft SDK notice hash mismatch')
                text += [f'--- {item["file"]} ---', data.decode('utf-8'), '']
            vendor_components.append(sdk)
        # Use the installed compiler distribution's library-only notice, not its full compiler/tool inventory.
        sysroot = Path(subprocess.check_output(['rustc', '--print', 'sysroot'], text=True).strip())
        rust_notice = sysroot / 'share/doc/rust/COPYRIGHT-library.html'
        if not rust_notice.is_file():
            raise RuntimeError('Rust standard-library copyright notice missing from toolchain')
        shutil.copyfile(rust_notice, stage / 'RUST-STANDARD-LIBRARY.html')
        (stage / 'THIRD-PARTY-NOTICES.txt').write_text('\n'.join(text) + '\n', encoding='utf-8')
        summary = {'schema_version': 1, 'target': target, 'lock_sha256': inventory['lock_sha256'],
                   'rustc': rust_version, 'rust_library_notice_sha256': digest(rust_notice.read_bytes()),
                   'packages': records, 'vendor_components': vendor_components}
        (stage / 'runtime-inventory.json').write_text(json.dumps(summary, indent=2, sort_keys=True) + '\n', encoding='utf-8')
        (stage / '.generated').write_text(MARKER, encoding='utf-8')
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(stage, destination)
        print(f'Prepared {len(records)} runtime dependency notices for {target} in {destination}')


if __name__ == '__main__':
    main()
